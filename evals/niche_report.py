"""David vs Goliath on the pre-registered niche (evals/niche.md) and on the honest slices.

Reads the predictions an eval run already produced (evals/runs/<run>/<variant>.jsonl), so it
needs no model and no network:

    uv run python evals/niche_report.py --run final-20261002 \
        --david tzij-2026-10-raft-bt-s3+hybrid+mbr4 --goliath gemini-3.8-flash

Writes evals/niche_results.md. Paired bootstrap over sentences (2,000 resamples, seed 2027)
for the corpus chrF++ difference and the win rate.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from sacrebleu.metrics import CHRF

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pipeline.niche import load_members  # noqa: E402

CHRF_PP = CHRF(word_order=2)
RESAMPLES, SEED = 2000, 2027
OUT = ROOT / "evals" / "niche_results.md"
SHOWABLE = {"bloom_kiche"}  # BOUQuET text stays private (its terms); only Bloom examples are quoted


def variant_file(run: Path, name: str) -> Path:
    return run / (name.replace(":", "_").replace("/", "_") + ".jsonl")


def load_rows(path: Path) -> dict[str, dict]:
    return {r["id"]: r for r in map(json.loads, path.read_text(encoding="utf-8").splitlines())}


def _stats(rows: list[dict]) -> np.ndarray:
    hyps = [r["text"] if r["status"] == "ok" else "" for r in rows]
    return np.array(CHRF_PP._extract_corpus_statistics(hyps, [[r["reference"] for r in rows]]), dtype=float)


def _score(stats: np.ndarray) -> float:
    return float(CHRF_PP._compute_score_from_stats(stats.sum(0).tolist()).score)


def compare(ids: list[str], david: dict[str, dict], goliath: dict[str, dict], seed: int = SEED) -> dict:
    """Corpus chrF++ for each side, difference and win rate, with paired bootstrap 95% CIs."""
    d_rows, g_rows = [david[i] for i in ids], [goliath[i] for i in ids]
    d_st, g_st = _stats(d_rows), _stats(g_rows)
    d_sent = np.array([r["chrf"] if r["status"] == "ok" else 0.0 for r in d_rows])
    g_sent = np.array([r["chrf"] if r["status"] == "ok" else 0.0 for r in g_rows])
    wins, ties = d_sent > g_sent, d_sent == g_sent
    rng = np.random.default_rng(seed)
    deltas, rates = [], []
    n = len(ids)
    for _ in range(RESAMPLES):
        idx = rng.integers(0, n, n)
        deltas.append(_score(d_st[idx]) - _score(g_st[idx]))
        rates.append(wins[idx].mean())
    lo, hi = np.percentile(deltas, [2.5, 97.5])
    rlo, rhi = np.percentile(rates, [2.5, 97.5])
    d, g = _score(d_st), _score(g_st)
    verdict = "David" if lo > 0 else "Goliath" if hi < 0 else "empate"
    return {"n": n, "david": d, "goliath": g, "delta": d - g, "ci": (float(lo), float(hi)),
            "win_rate": float(wins.mean()), "win_ci": (float(rlo), float(rhi)), "ties": int(ties.sum()),
            "verdict": verdict}


def _row(label: str, c: dict) -> str:
    return (f"| {label} | {c['n']} | {c['david']:.1f} | {c['goliath']:.1f} | **{c['delta']:+.1f}** "
            f"[{c['ci'][0]:+.1f}, {c['ci'][1]:+.1f}] | {100 * c['win_rate']:.0f}% "
            f"[{100 * c['win_ci'][0]:.0f}, {100 * c['win_ci'][1]:.0f}] | {c['ties']} | {c['verdict']} |")


HEADER = ("| slice | n | David chrF++ | Goliath chrF++ | David − Goliath [95% CI] | David wins [95% CI] | ties | verdict |\n"
          "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |")


def _bucket(words: int) -> str:
    return "short phrase (1–4 words)" if words <= 4 else "sentence (5–12 words)" if words <= 12 else "long sentence (13+ words)"


def build_report(run: Path, david_name: str, goliath_name: str, test: Path) -> tuple[str, dict]:
    david, goliath = load_rows(variant_file(run, david_name)), load_rows(variant_file(run, goliath_name))
    records = {r["id"]: r for r in map(json.loads, test.read_text(encoding="utf-8").splitlines())}
    ids = sorted(set(david) & set(goliath) & set(records))
    members = load_members()
    niche = [i for i in ids if (records[i]["pair_id"], records[i]["direction"]) in members]

    out: dict = {"niche": compare(niche, david, goliath), "all": compare(ids, david, goliath)}
    lines = [
        "# Niche results — David vs Goliath",
        "",
        f"Generated by `evals/niche_report.py` from run `{run.name}`. David = `{david_name}`, "
        f"Goliath = `{goliath_name}`. Niche definition (pre-registered, not changed after this): "
        "[`evals/niche.md`](niche.md); frozen members: `evals/niche_members.json`.",
        "",
        "Verdict rule: David wins only if the whole 95% interval of the corpus chrF++ difference is above 0; "
        "if it contains 0 it is a tie (`empate`). Win rate = share of sentences where David's sentence chrF++ "
        f"is strictly higher. Paired bootstrap, {RESAMPLES:,} resamples, seed {SEED}.",
        "",
        "## The niche: vocabulary from our dictionaries, rare in web K'iche'",
        "",
        HEADER,
        _row("niche, both directions", out["niche"]),
    ]
    for d, label in (("es-quc", "niche, español → K'iche'"), ("quc-es", "niche, K'iche' → español")):
        sub = [i for i in niche if records[i]["direction"] == d]
        if sub:
            out[f"niche {d}"] = compare(sub, david, goliath)
            lines.append(_row(label, out[f"niche {d}"]))
    rest = [i for i in ids if i not in set(niche)]
    out["outside"] = compare(rest, david, goliath)
    lines.append(_row("outside the niche", out["outside"]))

    lines += ["", "## Honest slices (whole test sample)", "", HEADER, _row("all", out["all"])]
    groups: dict[str, list[str]] = defaultdict(list)
    for i in ids:
        r = records[i]
        groups["direction: " + ("español → K'iche'" if r["direction"] == "es-quc" else "K'iche' → español")].append(i)
        groups["length: " + _bucket(len(r["source_text"].split()))].append(i)
        groups["source: " + r["source_name"]].append(i)
        groups["domain: " + r["domain"]].append(i)
    for key in sorted(groups):
        if len(groups[key]) >= 10:
            out[key] = compare(groups[key], david, goliath)
            lines.append(_row(key, out[key]))

    shown = sorted((i for i in niche if records[i]["source_name"] in SHOWABLE and david[i]["chrf"] > goliath[i]["chrf"]),
                   key=lambda i: goliath[i]["chrf"] - david[i]["chrf"])[:6]
    if shown:
        lines += ["", "## Examples where David wins inside the niche (Bloom only)", "",
                  "Illustrations, not evidence: the six largest David − Goliath gaps among niche sentences from "
                  "Bloom (BOUQuET text stays private). Both translations are unvalidated model output.", ""]
        for i in shown:
            r = records[i]
            lines += [f"- **{r['direction']}** · `{r['pair_id']}` · {r['url']}",
                      f"  - source: {r['source_text']}",
                      f"  - reference: {r['target_text']}",
                      f"  - David ({david[i]['chrf']:.1f}): {david[i]['text']}",
                      f"  - Goliath ({goliath[i]['chrf']:.1f}): {goliath[i]['text']}"]
    return "\n".join(lines) + "\n", out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--run", required=True)
    ap.add_argument("--david", required=True)
    ap.add_argument("--goliath", required=True)
    ap.add_argument("--dataset", type=Path, default=None)
    ap.add_argument("--json", type=Path, default=None, help="also dump the numbers as JSON")
    args = ap.parse_args()
    processed = ROOT / "data" / "processed"
    dataset = args.dataset or processed / (processed / "LATEST").read_text().strip()
    text, numbers = build_report(ROOT / "evals" / "runs" / args.run, args.david, args.goliath, dataset / "test.jsonl")
    OUT.write_text(text, encoding="utf-8")
    if args.json:
        args.json.write_text(json.dumps(numbers, indent=1), encoding="utf-8")
    c = numbers["niche"]
    print(f"niche n={c['n']} David {c['david']:.1f} Goliath {c['goliath']:.1f} "
          f"delta {c['delta']:+.1f} [{c['ci'][0]:+.1f}, {c['ci'][1]:+.1f}] win {100 * c['win_rate']:.0f}% -> {c['verdict']}")


if __name__ == "__main__":
    main()
